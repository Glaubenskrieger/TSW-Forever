#!/usr/bin/env python3
"""Generate website/css/themes.css from the launcher's own theme table (launcher-gui/src/theme.rs, the only place that defines the colours).

The web site shows the three faction themes of the launcher (Templars, Illuminati, Dragon) with exactly the values of the window, so the two cannot drift apart:
`scripts/test_website.py` regenerates the file in memory and fails if the committed `website/css/themes.css` differs.

  scripts/gen_website_themes.py            write website/css/themes.css
  scripts/gen_website_themes.py --check    exit 1 if the file is not up to date (writes nothing)

Only colours are taken over. `--ornament` (the subtle accent of a faction: gold for the Templars, cool light for the Illuminati, a pale green for the Dragon) is one of the theme's own
colours (`warn` or `focus_ring`), not a new one.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SOURCE = os.path.join(ROOT, "launcher-gui", "src", "theme.rs")
TARGET = os.path.join(ROOT, "website", "css", "themes.css")
FACTIONS = ("templars", "illuminati", "dragon")
ORNAMENT = {"templars": "warn", "illuminati": "focus_ring", "dragon": "focus_ring"}
FIELDS = ["ink", "card", "card_line", "text", "dim", "faint", "accent", "accent_hot", "accent_deep", "ok", "warn", "bad", "bg_start", "bg_mid", "bg_end", "glow", "hover_hi", "hover_lo",
          "hover_border", "btn_border", "btn_hover", "btn_base", "btn_primary", "frame", "shadow", "focus_ring"]


def parse(text):
    """{theme id: {field: '#rrggbb' or 'rgba(r, g, b, a)'}} for every ThemeDef of theme.rs."""
    themes = {}
    for block in re.split(r"ThemeDef \{", text)[1:]:
        m = re.search(r'id: "([a-z]+)"', block)
        if not m:
            continue
        values = {}
        for field, kind, rgb, alpha in re.findall(r"^\s+([a-z_]+): (o|a)\(0x([0-9a-fA-F]{6})(?:, 0x([0-9a-fA-F]{2}))?\)", block, re.M):
            if kind == "o":
                values[field] = "#" + rgb.lower()
            else:
                r, g, b = (int(rgb[i:i + 2], 16) for i in (0, 2, 4))
                values[field] = f"rgba({r}, {g}, {b}, {int(alpha, 16) / 255:.2f})"
        themes[m.group(1)] = values
    return themes


def render(themes):
    out = ["/* GENERATED by scripts/gen_website_themes.py from launcher-gui/src/theme.rs: do not edit by hand. */", ""]
    for tid in FACTIONS:
        t = themes[tid]
        missing = [f for f in FIELDS if f not in t]
        if missing:
            raise SystemExit(f"theme {tid}: missing fields {missing}")
        sel = f'[data-theme="{tid}"]' if tid != "templars" else f':root,\n[data-theme="templars"]'
        out.append(sel + " {")
        for f in FIELDS:
            out.append(f"  --{f.replace('_', '-')}: {t[f]};")
        out.append(f"  --ornament: {t[ORNAMENT[tid]]};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def main(argv):
    with open(SOURCE, encoding="utf-8") as f:
        css = render(parse(f.read()))
    if "--check" in argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if current != css:
            print("website/css/themes.css is not up to date: run scripts/gen_website_themes.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(css)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
